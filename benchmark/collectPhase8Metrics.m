function [summary, detail] = collectPhase8Metrics(scenario, result)
%COLLECTPHASE8METRICS Derive scalar and structured benchmark evidence.

    log = result.log;
    states = {log.acargState};
    transitionIndices = find(~strcmp(states(2:end), states(1:end - 1))) + 1;
    transitionTimes = [log(transitionIndices).time];
    transitionLabels = cell(numel(transitionIndices), 1);
    for i = 1:numel(transitionIndices)
        index = transitionIndices(i);
        transitionLabels{i} = sprintf('%s -> %s', ...
            log(index - 1).acargState, log(index).acargState);
    end

    events = result.planEvents;
    if isempty(events)
        latencies = NaN;
    else
        replanMask = ~[events.initialPlan];
        if any(replanMask)
            latencies = [events(replanMask).latencySeconds];
        else
            latencies = [events.latencySeconds];
        end
    end
    speeds = [log.egoSpeed];
    stopped = speeds <= 0.05;
    stopStarts = stopped & [true ~stopped(1:end - 1)];
    steering = [log.steering];
    actorMetrics = collectActorMetrics(scenario, result);
    if isempty(actorMetrics)
        highestRiskActorID = NaN;
        highestRiskActorClass = "";
        peakActorRisk = NaN;
    else
        [peakActorRisk, index] = max([actorMetrics.maximumActorRisk]);
        highestRiskActorID = actorMetrics(index).ActorID;
        highestRiskActorClass = string(actorMetrics(index).Class);
    end
    safeTermination = ~result.collisionOccurred && ~result.goalReached && ...
        (startsWith(result.terminationReason, 'Safely stopped') || ...
        strcmp(result.terminationReason, 'Maximum simulation time reached safely.'));
    completed = result.goalReached && ~result.collisionOccurred;
    completionTime = NaN;
    if result.goalReached
        completionTime = result.simulationTime;
    end
    unsafeFrames = sum(~[log.pathSafe]);
    unsafeMovingFrames = sum(~[log.pathSafe] & speeds > 0.05);

    summary = struct('Scenario', string(scenario.name), ...
        'ScenarioCompleted', completed, 'GoalReached', result.goalReached, ...
        'Collision', result.collisionOccurred, 'SafeTermination', safeTermination, ...
        'TerminationReason', string(result.terminationReason), ...
        'SimulationTime', result.simulationTime, 'CompletionTime', completionTime, ...
        'FinalGoalError', result.goalDistanceError, ...
        'Distance', result.distanceTravelled, ...
        'InitialPathLength', result.initialPathLength, ...
        'Replans', result.numberOfReplans, ...
        'SuccessfulReplans', sum([events.success] & ~[events.initialPlan]), ...
        'FailedReplans', result.numberOfFailedReplans, ...
        'MeanReplanLatencyMs', 1000 * mean(latencies, 'omitnan'), ...
        'MedianReplanLatencyMs', 1000 * median(latencies, 'omitnan'), ...
        'MaxReplanLatencyMs', 1000 * max(latencies, [], 'omitnan'), ...
        'MeanSpeed', mean(speeds), 'MaxSpeed', max(speeds), ...
        'MinActorDistance', result.metrics.minimumActorDistance, ...
        'MeanRisk', result.metrics.meanRisk, ...
        'MaxRisk', result.metrics.maximumRisk, ...
        'MinRisk', min([log.totalRisk]), ...
        'RiskRange', range([log.totalRisk]), ...
        'NormalTime', result.metrics.timeInNORMAL, ...
        'CautiousTime', result.metrics.timeInCAUTIOUS, ...
        'StopTime', result.metrics.timeInCONSERVATIVE_STOP, ...
        'StateTransitions', numel(transitionIndices), ...
        'Stops', sum(stopStarts), 'ActivePathUnsafeFrames', unsafeFrames, ...
        'UnsafeMovingFrames', unsafeMovingFrames, ...
        'PlannerInvocations', sum([log.plannerInvoked]), ...
        'PathChangeCount', sum([events.pathReplaced]), ...
        'RMSSteering', sqrt(mean(steering .^ 2)), ...
        'CumulativeSteeringChange', sum(abs(diff(steering))), ...
        'MinimumSpeedScale', min([log.speedScale]), ...
        'MaximumSafetyScale', max([log.safetyScale]), ...
        'ReplanRequestedEvents', sum([log.replanRequested]), ...
        'PeakActorRisk', peakActorRisk, ...
        'HighestRiskActorID', highestRiskActorID, ...
        'HighestRiskActorClass', highestRiskActorClass);
    detail = struct('scenarioName', scenario.name, ...
        'statesObserved', {unique(states, 'stable')}, ...
        'transitionTimes', transitionTimes, ...
        'transitionLabels', {transitionLabels}, ...
        'actorMetrics', actorMetrics, 'planEvents', events, ...
        'log', log, 'egoHistory', result.egoHistory, ...
        'actorHistory', result.actorHistory);
end

function metrics = collectActorMetrics(scenario, result)
    actors = scenario.actors;
    template = struct('ActorID', [], 'Class', '', 'maximumActorRisk', 0, ...
        'maximumUncertainty', 0, 'minimumActorDistance', inf, ...
        'maximumAdaptiveScale', 1);
    metrics = repmat(template, numel(actors), 1);
    for actorIndex = 1:numel(actors)
        actorID = actors(actorIndex).ID;
        maxRisk = 0;
        maxUncertainty = 0;
        maxScale = 1;
        for frame = 1:numel(result.log)
            details = result.log(frame).actorRiskDetails;
            match = find([details.ActorID] == actorID, 1);
            if ~isempty(match)
                maxRisk = max(maxRisk, details(match).risk);
                maxUncertainty = max(maxUncertainty, details(match).uncertainty);
                maxScale = max(maxScale, details(match).safetyScale * ...
                    result.log(frame).safetyScale);
            end
        end
        actorXY = squeeze(result.actorHistory(actorIndex, 1:2, :)).';
        egoXY = result.egoHistory(:, 1:2);
        frameCount = min(size(actorXY, 1), size(egoXY, 1));
        distances = hypot(actorXY(1:frameCount, 1) - egoXY(1:frameCount, 1), ...
            actorXY(1:frameCount, 2) - egoXY(1:frameCount, 2));
        metrics(actorIndex) = struct('ActorID', actorID, ...
            'Class', actors(actorIndex).TrueClass, ...
            'maximumActorRisk', maxRisk, ...
            'maximumUncertainty', maxUncertainty, ...
            'minimumActorDistance', min(distances), ...
            'maximumAdaptiveScale', maxScale);
    end
end
