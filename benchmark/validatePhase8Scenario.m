function report = validatePhase8Scenario(scenario)
%VALIDATEPHASE8SCENARIO Check common schema, geometry, and initial planning.

    required = {'name', 'description', 'egoInitialState', 'egoState', ...
        'goalPose', 'actors', 'maxSimulationTime', 'expectedBehavior', ...
        'seed', 'config'};
    missing = required(~isfield(scenario, required));
    if ~isempty(missing)
        error('validatePhase8Scenario:MissingField', ...
            'Scenario %s is missing %s.', scenario.name, strjoin(missing, ', '));
    end
    egoValues = [scenario.egoState.x scenario.egoState.y ...
        scenario.egoState.yaw scenario.egoState.speed];
    if any(~isfinite(egoValues)) || numel(scenario.goalPose) ~= 3 || ...
            any(~isfinite(scenario.goalPose)) || isempty(scenario.actors)
        error('validatePhase8Scenario:InvalidGeometry', ...
            'Scenario %s has an invalid ego, goal, or actor list.', scenario.name);
    end
    for i = 1:numel(scenario.actors)
        actor = scenario.actors(i);
        if any(~isfinite(actor.Position)) || any(~isfinite(actor.Velocity))
            error('validatePhase8Scenario:InvalidActor', ...
                'Scenario %s actor %d is not finite.', scenario.name, i);
        end
        finalPosition = actor.Position(1:2) + ...
            actor.Velocity(1:2) * scenario.maxSimulationTime;
        bounds = scenario.config.occupancy.worldLimits;
        if finalPosition(1) < bounds(1, 1) || finalPosition(1) > bounds(1, 2) || ...
                finalPosition(2) < bounds(2, 1) || finalPosition(2) > bounds(2, 2)
            error('validatePhase8Scenario:ActorLeavesWorld', ...
                'Scenario %s actor %d leaves configured world bounds.', ...
                scenario.name, i);
        end
    end
    [collision, minimumDistance] = checkCollision(scenario.egoState, ...
        scenario.actors, scenario.config);
    if collision
        error('validatePhase8Scenario:InitialCollision', ...
            'Scenario %s begins in collision.', scenario.name);
    end
    [tracks, ~] = updateActorTracks(struct([]), scenario.actors, ...
        scenario.egoState, 0, scenario.config);
    riskMap = updateOccupancyMap(tracks, scenario.egoState, scenario.config);
    acarg = acargGovernor(tracks, scenario.egoState, scenario.config, []);
    adaptiveMap = applyAdaptiveSafetyEnvelope(riskMap, acarg, scenario.config);
    planner = createPlanner(adaptiveMap, scenario.config);
    startPose = [scenario.egoState.x scenario.egoState.y scenario.egoState.yaw];
    startValid = isStateValid(planner.Validator, startPose);
    goalValid = isStateValid(planner.Validator, scenario.goalPose);
    initialPath = planPath(planner, startPose, scenario.goalPose, scenario.config);
    if ~startValid || ~goalValid || ~initialPath.success
        error('validatePhase8Scenario:InitialPlan', ...
            ['Scenario %s initial planning failed: startValid=%d, ' ...
            'goalValid=%d, reason=%s'], scenario.name, startValid, goalValid, ...
            initialPath.failureReason);
    end
    report = struct('scenarioName', scenario.name, 'valid', true, ...
        'startValid', startValid, 'goalValid', goalValid, ...
        'initialCollision', collision, 'minimumActorDistance', minimumDistance, ...
        'initialOccupiedCells', nnz(adaptiveMap.conservativeOccupancyMask), ...
        'initialPathLength', initialPath.length, 'initialState', acarg.state, ...
        'initialRisk', acarg.risk.totalRisk);
end
