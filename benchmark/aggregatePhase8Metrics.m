function aggregate = aggregatePhase8Metrics(summaryTable, totalWallClockSeconds)
%AGGREGATEPHASE8METRICS Compute system-level rates and worst cases.

    total = height(summaryTable);
    completed = sum(summaryTable.ScenarioCompleted);
    goals = sum(summaryTable.GoalReached);
    collisions = sum(summaryTable.Collision);
    aggregate = struct('totalScenarios', total, ...
        'completedScenarios', completed, 'goalReachedCount', goals, ...
        'collisionCount', collisions, ...
        'completionRate', completed / total, ...
        'goalReachRate', goals / total, ...
        'collisionFreeRate', (total - collisions) / total, ...
        'meanCompletionTime', mean(summaryTable.CompletionTime, 'omitnan'), ...
        'meanDistanceTravelled', mean(summaryTable.Distance), ...
        'meanReplansPerScenario', mean(summaryTable.Replans), ...
        'totalFailedReplans', sum(summaryTable.FailedReplans), ...
        'meanReplanLatencyMs', mean(summaryTable.MeanReplanLatencyMs, 'omitnan'), ...
        'worstCaseReplanLatencyMs', max(summaryTable.MaxReplanLatencyMs), ...
        'meanMinimumActorDistance', mean(summaryTable.MinActorDistance), ...
        'globalMaximumRisk', max(summaryTable.MaxRisk), ...
        'totalBenchmarkWallClockSeconds', totalWallClockSeconds);
    [~, index] = max(summaryTable.MaxRisk);
    aggregate.scenarioWithHighestRisk = char(summaryTable.Scenario(index));
    [~, index] = min(summaryTable.MinActorDistance);
    aggregate.scenarioWithSmallestClearance = char(summaryTable.Scenario(index));
    [~, index] = max(summaryTable.Replans);
    aggregate.scenarioWithMostReplans = char(summaryTable.Scenario(index));
    completedIndices = find(summaryTable.GoalReached);
    if isempty(completedIndices)
        aggregate.scenarioWithLongestCompletionTime = '';
    else
        [~, localIndex] = max(summaryTable.CompletionTime(completedIndices));
        aggregate.scenarioWithLongestCompletionTime = ...
            char(summaryTable.Scenario(completedIndices(localIndex)));
    end
    [~, index] = max(summaryTable.MaxReplanLatencyMs);
    aggregate.scenarioWithLargestReplanLatency = char(summaryTable.Scenario(index));
end
