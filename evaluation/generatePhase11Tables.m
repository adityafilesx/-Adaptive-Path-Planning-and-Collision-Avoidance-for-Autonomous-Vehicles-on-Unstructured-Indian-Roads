function tables = generatePhase11Tables(evaluation)
%GENERATEPHASE11TABLES Package report/PPT-ready table set.

    tables=struct('scenarioMetrics',evaluation.dataset.scenarioMetrics, ...
        'baselineComparison',evaluation.baseline.table, ...
        'ablationResults',evaluation.ablation.resultsTable, ...
        'stateTransitions',evaluation.stateTransitions, ...
        'robustnessSummary',evaluation.robustness.summaryTable, ...
        'headlineMetrics',evaluation.statisticalSummary.headlineMetrics);
end
