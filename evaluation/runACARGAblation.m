function ablation = runACARGAblation(cfg)
%RUNACARGABLATION Focused one-factor counterfactual evidence.

    if nargin<1||isempty(cfg),cfg=config();end
    confidence=confidenceExperiment(cfg);
    cpa=cpaExperiment(cfg);
    actorClass=classExperiment(cfg);
    envelope=envelopeExperiment(cfg);
    ablation=struct('confidence',confidence,'cpa',cpa, ...
        'actorClass',actorClass,'adaptiveEnvelope',envelope, ...
        'resultsTable',vertcat(confidenceToCommon(confidence), ...
            cpaToCommon(cpa),classToCommon(actorClass),envelopeToCommon(envelope)));
end

function table=confidenceExperiment(cfg)
inputs=[0.95;0.80;0.60;0.40]; rows=cell(2*numel(inputs),1); k=0;
for mode=["FULL_ACARG","NO_CONFIDENCE_EFFECT"]
    previous=[];
    for i=1:numel(inputs)
        input=inputs(i); actual=input; stdValue=0.10+1.50*(1-input);
        if mode=="NO_CONFIDENCE_EFFECT",actual=0.95;stdValue=0.10+1.50*0.05;end
        [actor,decision]=evaluateActor(cfg,'pedestrian',[22 6],[0 -1.2],actual,stdValue,previous);
        previous=decision; k=k+1;
        rows{k}=struct('Mode',mode,'DetectionConfidence',input, ...
            'EffectiveDetectionConfidence',actual,'TrustScore',actor.confidence, ...
            'Uncertainty',actor.uncertainty,'ActorRisk',actor.risk, ...
            'AdaptiveScale',actor.combinedAdaptiveScale, ...
            'GovernorState',string(decision.state),'SpeedScale',decision.speedScale);
    end
end
table=struct2table(vertcat(rows{:}));
end
function table=cpaExperiment(cfg)
defs={struct('name',"Closer moving away",'position',[10 0],'velocity',[7 0]), ...
    struct('name',"Farther collision course",'position',[18 6],'velocity',[0 -4/3])};
rows=cell(6,1); k=0;
for i=1:numel(defs)
    [actor,~]=evaluateActor(cfg,'car',defs{i}.position,defs{i}.velocity,0.95,0.1,[]);
    diag=actor.collisionDiagnostics;
    risks=[actor.risk, counterfactualRisk(actor,diag.timeWeightedDistanceComponent,cfg), ...
        min(1,actor.classWeight*actor.distanceRisk)];
    modes=["FULL_ACARG","NO_CPA_EFFECT","DISTANCE_ONLY"];
    for j=1:3
        k=k+1; rows{k}=struct('Geometry',defs{i}.name,'Mode',modes(j), ...
            'PhysicalDistance',actor.distance,'CPADistance',diag.cpaDistance, ...
            'CPATime',diag.cpaTime,'DistanceRisk',actor.distanceRisk, ...
            'CollisionRisk',actor.collisionRisk,'ActorRisk',risks(j));
    end
end
table=struct2table(vertcat(rows{:}));
end
function value=counterfactualRisk(actor,collisionRisk,cfg)
raw=actor.rawRisk-cfg.governor.risk.wCollision*actor.collisionRisk+ ...
    cfg.governor.risk.wCollision*collisionRisk;
value=min(1,max(0,actor.classWeight*raw));
end
function table=classExperiment(cfg)
classes=["car","pedestrian","cattle"]; rows=cell(6,1); k=0;
[neutralCfg,~]=createEvaluationMode(cfg,'NO_CLASS_WEIGHTING');
for mode=["FULL_ACARG","NO_CLASS_WEIGHTING"]
    activeCfg=cfg;if mode=="NO_CLASS_WEIGHTING",activeCfg=neutralCfg;end
    for i=1:numel(classes)
        [actor,~]=evaluateActor(activeCfg,classes(i),[18 6],[0 -4/3],0.95,0.1,[]);
        k=k+1;rows{k}=struct('Mode',mode,'ActorClass',classes(i), ...
            'PhysicalDistance',actor.distance,'ClassWeight',actor.classWeight, ...
            'ActorRisk',actor.risk,'AdaptiveScale',actor.combinedAdaptiveScale);
    end
end
table=struct2table(vertcat(rows{:}));
end
function table=envelopeExperiment(cfg)
defs={struct('name',"Stable car",'class',"car",'confidence',0.95,'std',0.1), ...
    struct('name',"Low-confidence pedestrian",'class',"pedestrian",'confidence',0.40,'std',1.0), ...
    struct('name',"Crossing cattle",'class',"cattle",'confidence',0.80,'std',0.4)};
rows=cell(6,1);k=0;
for i=1:numel(defs)
    [actor,~]=evaluateActor(cfg,defs{i}.class,[18 6],[0 -4/3], ...
        defs{i}.confidence,defs{i}.std,[]);
    for mode=["FIXED_MARGIN_BASELINE","FULL_ACARG"]
        k=k+1;scale=1;if mode=="FULL_ACARG",scale=actor.combinedAdaptiveScale;end
        rows{k}=struct('Actor',defs{i}.name,'ActorClass',defs{i}.class, ...
            'Mode',mode,'ActorRisk',actor.risk, ...
            'BaseExtentX',actor.baseSafetyExtentX,'BaseExtentY',actor.baseSafetyExtentY, ...
            'EffectiveExtentX',actor.baseSafetyExtentX*scale, ...
            'EffectiveExtentY',actor.baseSafetyExtentY*scale,'AdaptiveScale',scale);
    end
end
table=struct2table(vertcat(rows{:}));
end
function [actor,decision]=evaluateActor(cfg,actorClass,position,velocity,confidence,stdValue,previous)
cfg=configurePhase8Scenario(cfg,10,1111);
d=struct('ID',1101,'Position',[position 0],'Velocity',[velocity 0], ...
    'PerceivedClass',char(actorClass),'TrueClass',char(actorClass), ...
    'PositionStd',[stdValue stdValue 0.1],'VelocityStd',[0.1 0.1 0.1], ...
    'IsDetected',true,'Confidence',confidence);
track=initializeTracker(d,cfg.control.dt,cfg,0);
ego=struct('Position',[0 0 0],'Velocity',[4 0 0]);
decision=acargGovernor(track,ego,cfg,previous); actor=decision.risk.actorRisk;
end
function common=confidenceToCommon(t)
common=table(repmat("CONFIDENCE",height(t),1),t.Mode,string(t.DetectionConfidence), ...
    t.DetectionConfidence,NaN(height(t),1),NaN(height(t),1),NaN(height(t),1), ...
    NaN(height(t),1),t.ActorRisk,t.AdaptiveScale,t.GovernorState,t.SpeedScale, ...
    NaN(height(t),1),NaN(height(t),1),NaN(height(t),1),NaN(height(t),1), ...
    'VariableNames',commonNames());
end
function common=cpaToCommon(t)
common=table(repmat("CPA",height(t),1),t.Mode,t.Geometry,NaN(height(t),1), ...
    t.PhysicalDistance,t.CPADistance,t.CPATime,NaN(height(t),1),t.ActorRisk, ...
    NaN(height(t),1),repmat("N/A",height(t),1),NaN(height(t),1), ...
    NaN(height(t),1),NaN(height(t),1),NaN(height(t),1),NaN(height(t),1), ...
    'VariableNames',commonNames());
end
function common=classToCommon(t)
common=table(repmat("ACTOR_CLASS",height(t),1),t.Mode,t.ActorClass,NaN(height(t),1), ...
    t.PhysicalDistance,NaN(height(t),1),NaN(height(t),1),t.ClassWeight,t.ActorRisk, ...
    t.AdaptiveScale,repmat("N/A",height(t),1),NaN(height(t),1), ...
    NaN(height(t),1),NaN(height(t),1),NaN(height(t),1),NaN(height(t),1), ...
    'VariableNames',commonNames());
end
function common=envelopeToCommon(t)
common=table(repmat("ADAPTIVE_ENVELOPE",height(t),1),t.Mode,t.Actor,NaN(height(t),1), ...
    NaN(height(t),1),NaN(height(t),1),NaN(height(t),1),NaN(height(t),1),t.ActorRisk, ...
    t.AdaptiveScale,repmat("N/A",height(t),1),NaN(height(t),1), ...
    t.BaseExtentX,t.BaseExtentY,t.EffectiveExtentX,t.EffectiveExtentY, ...
    'VariableNames',commonNames());
end
function names=commonNames()
names={'Experiment','Mode','Condition','DetectionConfidence','PhysicalDistance', ...
    'CPADistance','CPATime','ClassWeight','ActorRisk','AdaptiveScale', ...
    'GovernorState','SpeedScale','BaseExtentX','BaseExtentY', ...
    'EffectiveExtentX','EffectiveExtentY'};
end
