function text = summarizePhase11(evaluation)
%SUMMARIZEPHASE11 Format concise competition evidence without overclaiming.

    s=evaluation.statisticalSummary;o=evaluation.acargOverhead;
    text=sprintf([ ...
        'Authoritative benchmark: POST_PHASE9_FIX\n' ...
        'Main scenarios: %d | goal reached: %d | safe terminations: %d | collision-free: %d\n' ...
        'Robustness: %d scenarios | recovery %.1f%% | collision-free %.1f%%\n' ...
        'Replanning latency mean / p95 / maximum: %.3f / %.3f / %.3f ms\n' ...
        'Worst-latency scenario: %s\n' ...
        'Unsafe moving frames: %d\n' ...
        'Mean incremental ACARG overhead: %.3f ms (%.3f%% of %.0f ms period)\n'], ...
        s.mainScenarioCount,s.goalReachedCount,s.safeTerminationCount,s.collisionFreeCount, ...
        s.robustnessScenarioCount,100*s.robustnessRecoveryRate, ...
        100*s.robustnessCollisionFreeRate,s.meanPlannerLatencyMs, ...
        s.p95PlannerLatencyMs,s.maximumPlannerLatencyMs,s.worstLatencyScenario, ...
        s.unsafeMovingFrameCount,o.meanIncrementalOverheadMs,o.percentOfControlPeriod, ...
        o.controlPeriodMs);
end
