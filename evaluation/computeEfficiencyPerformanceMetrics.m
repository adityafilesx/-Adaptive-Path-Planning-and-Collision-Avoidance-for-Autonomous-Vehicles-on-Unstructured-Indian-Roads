function metrics = computeEfficiencyPerformanceMetrics(result,wallClockSeconds)
%COMPUTEEFFICIENCYPERFORMANCEMETRICS Measured MATLAB wall-clock timing.

    events=result.planEvents;
    if isempty(events), latencies=[]; else, latencies=[events.latencySeconds]; end
    frameCount=numel(result.log);
    metrics=struct('MeanReplanningLatencyMs',1000*mean(latencies,'omitnan'), ...
        'MedianReplanningLatencyMs',1000*median(latencies,'omitnan'), ...
        'P95ReplanningLatencyMs',1000*percentile95(latencies), ...
        'MaximumReplanningLatencyMs',1000*max(latencies,[],'omitnan'), ...
        'PlannerInvocationCount',numel(latencies), ...
        'TotalPlanningTimeMs',1000*sum(latencies,'omitnan'), ...
        'RunWallClockSeconds',wallClockSeconds, ...
        'FrameCount',frameCount, ...
        'EquivalentMeanFrameWallClockMs',1000*wallClockSeconds/max(1,frameCount), ...
        'RealTimeFactor',result.simulationTime/max(eps,wallClockSeconds));
end
function value=percentile95(values)
values=sort(values(isfinite(values)));
if isempty(values),value=NaN;return;end
index=1+(numel(values)-1)*0.95; low=floor(index); high=ceil(index);
if low==high,value=values(low);else,value=values(low)+(index-low)*(values(high)-values(low));end
end
