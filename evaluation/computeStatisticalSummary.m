function summary = computeStatisticalSummary(dataset,baseline,robustness,overhead,cfg)
%COMPUTESTATISTICALSUMMARY Aggregate deterministic evidence without p-values.

    t=dataset.scenarioMetrics; latencies=allPlannerLatencies(dataset);
    runFrameMeans=t.EquivalentMeanFrameWallClockMs;
    summary=struct('mainScenarioCount',height(t),'goalReachedCount',sum(t.GoalReached), ...
        'safeTerminationCount',sum(t.SafeTermination), ...
        'collisionFreeCount',sum(~t.Collision), ...
        'goalReachRate',mean(t.GoalReached),'collisionFreeRate',mean(~t.Collision), ...
        'meanMinimumActorClearance',mean(t.MinimumActorDistance), ...
        'worstMinimumActorClearance',min(t.MinimumActorDistance), ...
        'meanCompletionTime',mean(t.CompletionTime,'omitnan'), ...
        'meanReplans',mean(t.Replans),'totalFailedReplans',sum(t.FailedReplans), ...
        'meanPlannerLatencyMs',1000*mean(latencies), ...
        'medianPlannerLatencyMs',1000*median(latencies), ...
        'p95PlannerLatencyMs',1000*percentile95(latencies), ...
        'maximumPlannerLatencyMs',1000*max(latencies), ...
        'worstLatencyScenario',worstLatencyScenario(dataset), ...
        'meanEquivalentFrameWallClockMs',mean(runFrameMeans), ...
        'maximumEquivalentFrameWallClockMs',max(runFrameMeans), ...
        'robustnessScenarioCount',robustness.aggregate.totalScenarios, ...
        'robustnessCollisionFreeRate',robustness.aggregate.collisionFreeCount/robustness.aggregate.totalScenarios, ...
        'robustnessRecoveryRate',robustness.aggregate.recoveredCount/robustness.aggregate.totalScenarios, ...
        'robustnessSafeTerminationCount',robustness.aggregate.safeTerminationCount, ...
        'robustnessUnexplainedFailures',robustness.aggregate.unexplainedFailureCount, ...
        'unsafeMovingFrameCount',sum(t.ActivePathUnsafeMovingFrames)+ ...
            sum(robustness.summaryTable.ActivePathUnsafeMovingFrames), ...
        'stateTransitionCount',sum(t.StateTransitions)+sum(robustness.summaryTable.StateTransitions), ...
        'acargOverhead',overhead,'baselineDifferences',baseline.pairedDifferences, ...
        'controlTimestep',cfg.control.dt);
    summary.headlineMetrics=buildHeadline(summary);
end
function values=allPlannerLatencies(dataset)
values=[];
for i=1:numel(dataset.scenarioRuns)
    values=[values [dataset.scenarioRuns(i).result.planEvents.latencySeconds]]; %#ok<AGROW>
end
values=values(isfinite(values));
end
function name=worstLatencyScenario(dataset)
best=-inf;name="";
for i=1:numel(dataset.scenarioRuns)
    values=[dataset.scenarioRuns(i).result.planEvents.latencySeconds];
    if ~isempty(values)&&max(values)>best,best=max(values);name=string(dataset.scenarioRuns(i).scenario.name);end
end
end
function value=percentile95(values)
values=sort(values(:));index=1+(numel(values)-1)*.95;lo=floor(index);hi=ceil(index);
if lo==hi,value=values(lo);else,value=values(lo)+(index-lo)*(values(hi)-values(lo));end
end
function resultTable=buildHeadline(s)
metric=["Main deterministic scenario families";"Collision-free rate";"Goal reach rate"; ...
    "Safe terminations";"Worst observed actor clearance";"Robustness recovery rate"; ...
    "Unsafe active-path moving frames";"Mean replanning latency"; ...
    "95th-percentile replanning latency";"Maximum replanning latency"; ...
    "Mean incremental ACARG overhead";"Closed-loop control period"];
value=[s.mainScenarioCount;100*s.collisionFreeRate;100*s.goalReachRate; ...
    s.safeTerminationCount;s.worstMinimumActorClearance;100*s.robustnessRecoveryRate; ...
    s.unsafeMovingFrameCount;s.meanPlannerLatencyMs;s.p95PlannerLatencyMs; ...
    s.maximumPlannerLatencyMs;s.acargOverhead.meanIncrementalOverheadMs;1000*s.controlTimestep];
unit=["count";"percent";"percent";"count";"m";"percent";"frames"; ...
    "ms";"ms";"ms";"ms/frame";"ms"];
context=["Five Phase 8 families";"Tested deterministic main scenarios"; ...
    "Safe termination excluded from goal count";"Explicit non-goal safe outcomes"; ...
    "Across five main scenarios";"Eight controlled Phase 9 disturbances"; ...
    "Benchmark plus robustness";"MATLAB development hardware"; ...
    "MATLAB development hardware";"MATLAB development hardware"; ...
    "Recorded-track replay";"Configured controller timestep"];
resultTable=table(metric,value,unit,context, ...
    'VariableNames',{'Metric','Value','Unit','Context'});
end
