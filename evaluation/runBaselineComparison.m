function comparison = runBaselineComparison(dataset,cfg)
%RUNBASELINECOMPARISON Pair fixed-margin and ACARG runs on identical scenarios.

    if nargin<2||isempty(cfg),cfg=config();end
    [baselineCfg,baselineMetadata]=createEvaluationMode(cfg,'FIXED_MARGIN_BASELINE');
    selected=["Unsignalized Urban Intersection","Highway Slow-Vehicle Merge", ...
        "Dense Mixed-Traffic Market","Sudden Cattle Crossing"];
    rows=cell(2*numel(selected),1); pairs=cell(numel(selected),1); k=0;
    baselineScenarios=getPhase8Scenarios(baselineCfg);
    for i=1:numel(selected)
        fullIndex=find(dataset.scenarioMetrics.Scenario==selected(i),1);
        scenarioIndex=find(cellfun(@(s) string(s.name)==selected(i),baselineScenarios),1);
        assert(~isempty(fullIndex)&&~isempty(scenarioIndex),'Phase11:ScenarioMissing');
        fullRun=dataset.scenarioRuns(fullIndex); baselineScenario=baselineScenarios{scenarioIndex};
        assertSameInitialConditions(fullRun.scenario,baselineScenario);
        timer=tic; baselineResult=runClosedLoopSimulation(baselineScenario); wall=toc(timer);
        baselineMetrics=metricsFor(baselineScenario,baselineResult,wall);
        k=k+1; rows{k}=rowFor("ACARG_ENHANCED",fullRun.scenario,fullRun.result, ...
            fullRun.metrics,fullRun.wallClockSeconds,true);
        k=k+1; rows{k}=rowFor("FIXED_MARGIN_BASELINE",baselineScenario,baselineResult, ...
            baselineMetrics,wall,false);
        pairs{i}=struct('scenarioName',char(selected(i)),'fullRun',fullRun, ...
            'baselineScenario',baselineScenario,'baselineResult',baselineResult, ...
            'baselineMetrics',baselineMetrics);
    end
    table=struct2table(vertcat(rows{:}));
    difference=pairedDifferences(table);
    comparison=struct('table',table,'pairs',{pairs},'selectedScenarios',selected, ...
        'baselineMetadata',baselineMetadata,'pairedDifferences',difference);
end

function metrics=metricsFor(scenario,result,wall)
metrics=struct('safety',computeSafetyMetrics(scenario,result), ...
    'efficiency',computeEfficiencyMetrics(scenario,result), ...
    'smoothness',computeSmoothnessMetrics(result,scenario.config.control.dt), ...
    'riskResponse',computeRiskResponseMetrics(result), ...
    'performance',computeEfficiencyPerformanceMetrics(result,wall));
end
function row=rowFor(mode,scenario,result,m,wall,adaptive)
row=struct('Scenario',string(scenario.name),'Mode',string(mode), ...
    'GoalReached',m.safety.GoalReached,'SafeTermination',m.safety.SafeTermination, ...
    'Collision',m.safety.CollisionOccurred,'OutcomeClass',m.safety.OutcomeClass, ...
    'MinimumActorDistance',m.safety.MinimumActorDistance, ...
    'CompletionTime',m.efficiency.CompletionTime, ...
    'SimulationTime',m.efficiency.SimulationTime, ...
    'DistanceTravelled',m.efficiency.DistanceTravelled, ...
    'Replans',m.efficiency.NumberOfReplans, ...
    'FailedReplans',m.efficiency.NumberOfFailedReplans, ...
    'PathChanges',m.efficiency.NumberOfPathChanges, ...
    'MeanSpeed',m.efficiency.MeanSpeed,'MaximumRisk',m.riskResponse.MaximumRisk, ...
    'TimeStopped',m.efficiency.TimeStopped,'RMSSteering',m.smoothness.RMSSteering, ...
    'CumulativeSteeringChange',m.smoothness.CumulativeAbsoluteSteeringChange, ...
    'MeanPlannerLatencyMs',m.performance.MeanReplanningLatencyMs, ...
    'MaximumAdaptiveEnvelopeScale',m.riskResponse.MaximumAdaptiveEnvelopeScale, ...
    'UsesAdaptiveEnvelope',adaptive,'CollisionCheckingRetained',true, ...
    'WallClockSeconds',wall,'FiniteRun',all(isfinite(result.egoHistory(:))));
end
function assertSameInitialConditions(a,b)
assert(isequaln(a.egoInitialState,b.egoInitialState)&&isequaln(a.goalPose,b.goalPose)&& ...
    isequaln(a.actors,b.actors)&&a.config.control.dt==b.config.control.dt&& ...
    a.config.vehicle.length==b.config.vehicle.length&& ...
    a.config.vehicle.width==b.config.vehicle.width, ...
    'Phase11:InconsistentComparison','Baseline initial conditions differ.');
end
function d=pairedDifferences(t)
scenarios=unique(t.Scenario,'stable'); rows=cell(numel(scenarios),1);
for i=1:numel(scenarios)
    f=t(t.Scenario==scenarios(i)&t.Mode=="ACARG_ENHANCED",:);
    b=t(t.Scenario==scenarios(i)&t.Mode=="FIXED_MARGIN_BASELINE",:);
    rows{i}=struct('Scenario',scenarios(i), ...
        'ClearanceDifferenceM',f.MinimumActorDistance-b.MinimumActorDistance, ...
        'CompletionTimeDifferenceS',f.CompletionTime-b.CompletionTime, ...
        'ReplanDifference',f.Replans-b.Replans, ...
        'RMSSteeringDifferenceRad',f.RMSSteering-b.RMSSteering);
end
d=struct2table(vertcat(rows{:}));
end
