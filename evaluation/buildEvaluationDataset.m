function dataset = buildEvaluationDataset(cfg)
%BUILDEVALUATIONDATASET Rerun authoritative post-fix Phase 8 benchmark.

    if nargin<1||isempty(cfg),cfg=config();end
    assertCollisionRiskVersion(); scenarios=getPhase8Scenarios(cfg);
    runs=repmat(struct('scenario',[],'sanity',[],'result',[],'summary',[], ...
        'detail',[],'wallClockSeconds',0,'metrics',struct()),numel(scenarios),1);
    rows=cell(numel(scenarios),1); totalTimer=tic;
    for i=1:numel(scenarios)
        scenario=scenarios{i}; sanity=validatePhase8Scenario(scenario);
        timer=tic; result=runClosedLoopSimulation(scenario); wall=toc(timer);
        [summary,detail]=collectPhase8Metrics(scenario,result);
        safety=computeSafetyMetrics(scenario,result);
        efficiency=computeEfficiencyMetrics(scenario,result);
        smoothness=computeSmoothnessMetrics(result,scenario.config.control.dt);
        risk=computeRiskResponseMetrics(result);
        performance=computeEfficiencyPerformanceMetrics(result,wall);
        metrics=struct('safety',safety,'efficiency',efficiency, ...
            'smoothness',smoothness,'riskResponse',risk,'performance',performance);
        rows{i}=combineMetrics(scenario,summary,detail,metrics);
        runs(i)=struct('scenario',scenario,'sanity',sanity,'result',result, ...
            'summary',summary,'detail',detail,'wallClockSeconds',wall,'metrics',metrics);
    end
    wall=toc(totalTimer); table=struct2table(vertcat(rows{:}));
    benchmarkSummary=struct2table(vertcat(runs.summary));
    aggregate=aggregatePhase8Metrics(benchmarkSummary,wall);
    provenance=buildProvenance(cfg,wall);
    dataset=struct('scenarioRuns',runs,'scenarioMetrics',table, ...
        'summaryTable',benchmarkSummary,'aggregate',aggregate, ...
        'provenance',provenance);
end

