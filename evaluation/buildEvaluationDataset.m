function provenance=buildProvenance(cfg,wall)
root=fileparts(fileparts(mfilename('fullpath')));
files=dir(fullfile(root,'results','phase8','phase8Benchmark_*.mat'));
legacy=string(fullfile({files.folder},{files.name})).';
provenance=struct('generatedDate',string(datetime('now','TimeZone','local')), ...
    'gitCommit',"NOT_AVAILABLE_NOT_GIT_REPOSITORY", ...
    'collisionRiskVersion',"PHASE9_TIME_WEIGHTED_DISTANCE_V1", ...
    'benchmarkVersion',"POST_PHASE9_FIX", ...
    'scenarioVersion',"PHASE8_DETERMINISTIC_V1", ...
    'configSnapshot',cfg,'sourceResultFile',"generated by Phase 11 current rerun", ...
    'nonAuthoritativePriorPhase8Files',legacy, ...
    'legacyStatus',"NOT_AUTHORITATIVE; pre-fix artifacts are PRE_PHASE9_FIX", ...
    'benchmarkWallClockSeconds',wall);
end
function assertCollisionRiskVersion()
root=fileparts(fileparts(mfilename('fullpath')));
text=fileread(fullfile(root,'governor','computeCollisionRisk.m'));
assert(contains(text,'timeWeightedDistanceRisk = distRisk * timeRisk'), ...
    'Phase11:WrongRiskVersion','Required Phase 9 collision-risk correction is absent.');
end
