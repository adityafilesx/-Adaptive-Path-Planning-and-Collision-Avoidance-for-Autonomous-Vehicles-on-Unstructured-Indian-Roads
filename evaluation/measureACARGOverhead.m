function metrics = measureACARGOverhead(dataset,cfg)
%MEASUREACARGOVERHEAD Replay stored tracks to isolate governor wall-clock cost.

    if nargin<2||isempty(cfg),cfg=config();end
    acargTimes=zeros(0,1); fixedTimes=zeros(0,1);
    for r=1:numel(dataset.scenarioRuns)
        log=dataset.scenarioRuns(r).result.log;
        previous=[];
        for i=1:numel(log)
            ego=struct('Position',[log(i).egoX log(i).egoY 0], ...
                'Velocity',[log(i).egoSpeed*cos(log(i).egoYaw) ...
                    log(i).egoSpeed*sin(log(i).egoYaw) 0]);
            timer=tic; decision=acargGovernor(log(i).tracks,ego,cfg,previous);
            acargTimes(end+1,1)=toc(timer); %#ok<AGROW>
            timer=tic; fixedDecision(log(i).tracks); fixedTimes(end+1,1)=toc(timer); %#ok<AGROW>
            previous=decision;
        end
    end
    incremental=max(0,mean(acargTimes)-mean(fixedTimes));
    metrics=struct('sampleCount',numel(acargTimes), ...
        'meanACARGComputeTimeMs',1000*mean(acargTimes), ...
        'medianACARGComputeTimeMs',1000*median(acargTimes), ...
        'maximumACARGComputeTimeMs',1000*max(acargTimes), ...
        'meanFixedDecisionTimeMs',1000*mean(fixedTimes), ...
        'meanIncrementalOverheadMs',1000*incremental, ...
        'percentOfControlPeriod',100*incremental/cfg.control.dt, ...
        'controlPeriodMs',1000*cfg.control.dt, ...
        'measurementLabel',"MATLAB wall-clock replay on development hardware");
end
function value=fixedDecision(tracks)
value=struct('state',"NORMAL",'speedScale',1,'safetyScale',1, ...
    'replanRequested',false,'actorCount',numel(tracks));
end
