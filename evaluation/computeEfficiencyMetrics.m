function metrics = computeEfficiencyMetrics(scenario,result)
%COMPUTEEFFICIENCYMETRICS Completion, travel, speed, state-time, and planning.

    log=result.log; speeds=[log.egoSpeed]; dt=scenario.config.control.dt;
    directDistance=norm(scenario.goalPose(1:2)- ...
        [scenario.egoInitialState.x scenario.egoInitialState.y]);
    completionTime=NaN;
    if result.goalReached, completionTime=result.simulationTime; end
    metrics=struct('CompletionTime',completionTime, ...
        'SimulationTime',result.simulationTime, ...
        'DistanceTravelled',result.distanceTravelled, ...
        'InitialPathLength',result.initialPathLength, ...
        'FinalTravelDistance',result.distanceTravelled, ...
        'PathLengthOverStraightLineRatio',result.distanceTravelled/max(eps,directDistance), ...
        'NumberOfReplans',result.numberOfReplans, ...
        'NumberOfFailedReplans',result.numberOfFailedReplans, ...
        'NumberOfPathChanges',sum([result.planEvents.pathReplaced]), ...
        'MeanSpeed',mean(speeds),'MaximumSpeed',max(speeds), ...
        'TimeStopped',sum(speeds<=0.05)*dt, ...
        'TimeInNORMAL',sum(strcmp({log.acargState},'NORMAL'))*dt, ...
        'TimeInCAUTIOUS',sum(strcmp({log.acargState},'CAUTIOUS'))*dt, ...
        'TimeInCONSERVATIVE_STOP', ...
            sum(strcmp({log.acargState},'CONSERVATIVE_STOP'))*dt);
end
